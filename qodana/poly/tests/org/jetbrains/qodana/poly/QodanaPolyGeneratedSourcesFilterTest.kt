package org.jetbrains.qodana.poly

import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class QodanaPolyGeneratedSourcesFilterTest {
  @Test
  fun `lock files are generated`() {
    for (name in listOf("package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb", "go.sum", "go.work.sum")) {
      assertTrue(isGeneratedFileName(name), name)
    }
  }

  @Test
  fun `a minified name is generated`() {
    assertTrue(isGeneratedFileName("jquery.min.js"))
    assertTrue(isGeneratedFileName("styles.min.css"))
  }

  @Test
  fun `an ordinary name is not generated`() {
    for (name in listOf("app.js", "package.json", "main.go", "minify.js", "lock.json")) {
      assertFalse(isGeneratedFileName(name), name)
    }
  }

  @Test
  fun `the generated marker is read from the first line only`() {
    assertTrue(hasGeneratedMarker("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n"))
    assertFalse(hasGeneratedMarker("package api\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n"))
    assertFalse(hasGeneratedMarker("// Code generated by hand.\n"))
  }

  @Test
  fun `a long single line is minified`() {
    assertTrue(isMinifiedText("a".repeat(200) + "\n"))
  }

  @Test
  fun `formatted code is not minified`() {
    assertFalse(isMinifiedText(List(20) { "  var value$it = $it;" }.joinToString("\n")))
  }

  @Test
  fun `a short file is not minified`() {
    assertFalse(isMinifiedText("a".repeat(149)))
  }
}
