package org.jetbrains.qodana.poly

import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class QodanaPolyGeneratedSourcesFilterTest {
  @Test
  fun `lock files are generated`() {
    val names = listOf(
      "package-lock.json",
      "npm-shrinkwrap.json",
      "yarn.lock",
      "pnpm-lock.yaml",
      "bun.lock",
      "bun.lockb",
      "go.sum",
      "go.work.sum",
    )
    for (name in names) {
      assertTrue(isGeneratedFileName(name), name)
    }
  }

  @Test
  fun `a minified name is generated`() {
    assertTrue(isGeneratedFileName("jquery.min.js"))
    assertTrue(isGeneratedFileName("styles.min.css"))
  }

  @Test
  fun `a protoc name is generated`() {
    assertTrue(isGeneratedFileName("api.pb.go"))
    assertTrue(isGeneratedFileName("api.pb.gw.go"))
  }

  @Test
  fun `a source map is generated`() {
    assertTrue(isGeneratedFileName("bundle.js.map"))
    assertTrue(isGeneratedFileName("styles.css.map"))
  }

  @Test
  fun `an ordinary name is not generated`() {
    for (name in listOf("app.js", "package.json", "main.go", "minify.js", "lock.json")) {
      assertFalse(isGeneratedFileName(name), name)
    }
  }

  @Test
  fun `minified code is minified`() {
    assertTrue(isMinifiedText("function a(b,c){var d=b+c;return d}".repeat(120)))
    assertTrue(isMinifiedText(".a{color:red}.b{color:blue}".repeat(30)))
  }

  @Test
  fun `a license banner does not hide minified code`() {
    assertTrue(isMinifiedText("/*! lib v1.0 | MIT */\n" + "function a(b,c){var d=b+c;return d}".repeat(120)))
  }

  @Test
  fun `a long string constant is not minified`() {
    val code = List(20) { "  const value$it = $it;" }.joinToString("\n")
    assertFalse(isMinifiedText("const MSG = \"" + "x".repeat(2980) + "\";\n" + code))
  }

  @Test
  fun `a base64 data uri is not minified`() {
    val code = List(15) { "  paint$it();" }.joinToString("\n")
    assertFalse(isMinifiedText("const ICON = 'data:image/png;base64," + "A".repeat(1960) + "';\n" + code))
  }

  @Test
  fun `a one line license banner is not minified`() {
    val code = List(6) { "  const value$it = $it;" }.joinToString("\n")
    assertFalse(isMinifiedText("/* " + "L".repeat(900) + " */\n" + code))
  }

  @Test
  fun `unindented code with normal spacing is not minified`() {
    assertFalse(isMinifiedText(List(30) { "var value$it = $it;" }.joinToString("\n")))
  }

  @Test
  fun `a one line style rule is not minified`() {
    assertFalse(isMinifiedText("body { margin: 0; } ".repeat(20)))
  }

  @Test
  fun `formatted code is not minified`() {
    assertFalse(isMinifiedText(List(20) { "  var value$it = $it;" }.joinToString("\n")))
  }

  @Test
  fun `a short file is not minified`() {
    assertFalse(isMinifiedText("var a=1;".repeat(10)))
  }

  @Test
  fun `the generated marker marks a file`() {
    assertTrue(hasGoGeneratedMarker("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n"))
  }

  @Test
  fun `the generated marker is read from the whole comment region`() {
    val text = """
      //go:build linux
      // Copyright 2026 JetBrains s.r.o.

      // Code generated by mockgen. DO NOT EDIT.

      package api
    """.trimIndent()
    assertTrue(hasGoGeneratedMarker(text))
  }

  @Test
  fun `the generated marker after the first code line is ignored`() {
    assertFalse(hasGoGeneratedMarker("package api\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n"))
  }

  @Test
  fun `a hand written comment is not the generated marker`() {
    assertFalse(hasGoGeneratedMarker("// Code generated by hand.\n"))
    assertFalse(hasGoGeneratedMarker("package api\n"))
  }

  @Test
  fun `the scanner needs a normalized line separator`() {
    val body = "var a=1;".repeat(60) + "\n" + "var b=2;".repeat(60)
    assertTrue(isMinifiedText(body))
    assertFalse(isMinifiedText(body.replace("\n", "\r\n")))
  }

  @Test
  fun `whitespace next to a string literal is not minified`() {
    // The platform counts this through JSTokenTypes.STRING_LITERALS in NO_WHITESPACE_REQUIRED_BEFORE.
    val text = List(10) { "export ident from './$it'" }.joinToString("\n")
    assertFalse(isMinifiedText(text))
  }

  @Test
  fun `a formatted tail is not minified`() {
    assertTrue(isMinifiedTail("function a(b,c){var d=b+c;return d}".repeat(12)))
    assertFalse(isMinifiedTail(List(12) { "  const value$it = $it;" }.joinToString("\n")))
  }

  @Test
  fun `an unbalanced quote does not hide the indentation`() {
    val formatted = List(30) { "  var value$it = compute($it);" }.joinToString("\n")
    assertFalse(isMinifiedText("var re=/['\"]/;\n" + formatted), "a regular expression char class")
    assertFalse(isMinifiedText("<p>it's</p>\n" + formatted), "JSX text")
    assertFalse(isMinifiedText("var s='oops;\n" + formatted), "an unterminated string")
  }

  @Test
  fun `a template literal crosses a line break`() {
    assertTrue(isMinifiedText("var t=`a\nb`;function f(x){return x}".repeat(60)))
  }

  @Test
  fun `a string keeps its escaped quote`() {
    assertTrue(isMinifiedText("var s='it\\'s';function f(x){return x}".repeat(60)))
  }
}
