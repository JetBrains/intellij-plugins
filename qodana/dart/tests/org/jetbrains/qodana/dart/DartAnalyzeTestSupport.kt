package org.jetbrains.qodana.dart

import java.nio.file.Path

internal class RecordedDartAnalyzeProcessExecutor(
  private val projectPath: Path,
  private val analyzeResponses: Map<String, RecordedDartAnalyzeResponse>,
  private val preparationFailures: Map<String, String> = emptyMap(),
  private val executions: MutableList<Pair<String, String>> = mutableListOf(),
) : DartAnalyzeProcessExecutor {
  override suspend fun execute(command: List<String>, workingDirectory: Path): DartAnalyzeProcessResult {
    val modulePath = projectPath.toAbsolutePath().normalize().relativize(workingDirectory.toAbsolutePath().normalize()).portablePath()
    return when (command.getOrNull(1)) {
      "pub" -> {
        executions += "pub get" to modulePath
        logResponse("pub get", modulePath, "generated by mock")
        preparationFailures[modulePath]?.let { DartAnalyzeProcessResult(1, "", it) }
          ?: DartAnalyzeProcessResult(0, "", "")
      }
      "analyze" -> {
        executions += "analyze" to modulePath
        val response = analyzeResponses[modulePath] ?: error("No recorded Dart response for module '$modulePath'")
        logResponse("analyze", modulePath, "from fixture '${response.resourceName}'")
        DartAnalyzeProcessResult(0, response.content, "")
      }
      else -> error("Unexpected Dart command: $command")
    }
  }

  private fun logResponse(command: String, modulePath: String, source: String) {
    println("Dart mock: using response for '$command' in module '$modulePath' ($source)")
  }
}

internal class DartAnalyzeTestRunnerFactory(
  projectPath: Path,
  analyzeResponses: Map<String, RecordedDartAnalyzeResponse>,
  preparationFailures: Map<String, String> = emptyMap(),
  executions: MutableList<Pair<String, String>> = mutableListOf(),
) {
  private val recordedProcessExecutor = RecordedDartAnalyzeProcessExecutor(projectPath, analyzeResponses, preparationFailures, executions)
  private val recordedExecutableResolver = DartExecutableResolver { executableName ->
    DartExecutable.Available(Path.of(executableName))
  }

  fun create(): DartAnalyzeRunnerFactory = DartAnalyzeRunnerFactory { moduleType ->
    when (moduleType) {
      DartModuleType.DART -> if (isConfiguredExecutable("dart")) {
        DartExecutableRunner()
      }
      else {
        logRecordedRunner("dart")
        DartExecutableRunner(processExecutor = recordedProcessExecutor, executableResolver = recordedExecutableResolver)
      }
      DartModuleType.FLUTTER -> if (isConfiguredExecutable("flutter")) {
        FlutterExecutableRunner()
      }
      else {
        logRecordedRunner("flutter")
        FlutterExecutableRunner(processExecutor = recordedProcessExecutor, executableResolver = recordedExecutableResolver)
      }
    }
  }

  private fun isConfiguredExecutable(executableName: String): Boolean =
    configuredExecutableResolver({ System.getenv(FLUTTER_PATH_ENV) }).resolve(executableName) is DartExecutable.Available

  private fun logRecordedRunner(executableName: String) {
    println("Dart mock: using fallback runner for $executableName executable")
  }
}

internal object DartAnalyzeTestRunnerFactoryHolder {
  var factory: DartAnalyzeRunnerFactory? = null
}

internal class DartAnalyzeTestGlobalInspection : DartAnalyzeGlobalInspection(
  DartAnalyzeTestRunnerFactoryHolder.factory ?: error("Dart test runner factory is not configured"),
)

internal data class RecordedDartAnalyzeResponse(val resourceName: String, val content: String)

internal fun readDartAnalyzeTestData(name: String): RecordedDartAnalyzeResponse = RecordedDartAnalyzeResponse(
  name,
  requireNotNull(RecordedDartAnalyzeProcessExecutor::class.java.getResource("/dart-analyze/$name")) {
    "Missing Dart test data '$name'"
  }.readText(),
)

private fun Path.portablePath(): String = toString().replace('\\', '/')
